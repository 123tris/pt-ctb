using System.Linq;
using System.Text;

namespace PtCatch.Engine.Packs;

/// <summary>
/// web/src/gen/packs.ts from <see cref="Schemas"/>: an interface per pack (each column typed as the typed array it is),
/// its layout hash, and a reader. Only TypeScript that erases to JavaScript (no enums, no parameter properties), so
/// Node runs it as is and esbuild needs no type checker to bundle it.
/// </summary>
public static class GenTs
{
    public static string Generate()
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by `ptcatch-engine gen-ts` from engine/src/PtCatch.Engine/Packs/Schemas.cs. Don't edit: change the\n");
        sb.Append("// schema and run it again (`npm run gen`); a check fails while this file and the schema disagree.\n\n");
        sb.Append("import { readPack, type StrColumn } from '../kernel/ptcb.ts';\n\n");
        sb.Append("/** A grade's code in the `grade` columns is its index here (0 for none). */\n");
        sb.Append($"export const GRADES = [{string.Join(", ", Schemas.Grades.Select(g => $"'{g}'"))}] as const;\n\n");
        sb.Append("/** A bought name colour's code in `colour` is its index here (0 for none). */\n");
        sb.Append($"export const COLOURS = [{string.Join(", ", Schemas.Colours.Select(c => $"'{c}'"))}] as const;\n");
        foreach (var pack in Schemas.All)
        {
            var type = Pascal(pack.Name) + "Pack";
            sb.Append($"\n/** {pack.Doc} */\nexport interface {type} {{\n");
            foreach (var table in pack.Tables)
            {
                sb.Append($"  /** {table.Doc} */\n  {table.Name}: {{\n    rows: number;\n");
                foreach (var col in table.Cols)
                {
                    sb.Append($"    /** {col.Doc} */\n    {col.Name}: {TsType(col.Kind)};\n");
                }
                sb.Append("  };\n");
            }
            sb.Append("}\n\n");
            sb.Append($"export const {pack.Name.ToUpperInvariant()}_HASH = '{pack.Hash}';\n\n");
            sb.Append($"/** Reads a {pack.Name} pack, refusing one of another layout. */\n");
            sb.Append($"export const read{Pascal(pack.Name)} = (buffer: ArrayBuffer): {type} =>\n");
            sb.Append($"  readPack(buffer, '{pack.Name}', {pack.Name.ToUpperInvariant()}_HASH) as unknown as {type};\n");
        }
        return sb.ToString();
    }

    private static string Pascal(string name) => char.ToUpperInvariant(name[0]) + name[1..];

    private static string TsType(ColKind kind) => kind switch
    {
        ColKind.U8 => "Uint8Array",
        ColKind.U16 => "Uint16Array",
        ColKind.U32 => "Uint32Array",
        ColKind.I32 => "Int32Array",
        ColKind.F32 => "Float32Array",
        ColKind.F64 => "Float64Array",
        ColKind.D32 => "Uint32Array",
        _ => "StrColumn",
    };
}
